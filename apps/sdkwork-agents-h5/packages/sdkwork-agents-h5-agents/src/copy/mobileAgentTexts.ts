export function detectAgentH5Locale(): AgentH5Locale {
  const language =
    typeof navigator !== 'undefined' ? navigator.language : '';
  return language.toLowerCase().startsWith('en') ? 'en' : 'zh';
}

let activeAgentH5Locale: AgentH5Locale = detectAgentH5Locale();

/** Override the copy locale used by the mobile agent views (host hook). */
export function configureAgentH5Locale(locale: AgentH5Locale): void {
  activeAgentH5Locale = locale;
}

export function translateAgentMobileText(
  key: string,
  params?: Record<string, string>,
): string {
  const table = MOBILE_AGENT_COPY[activeAgentH5Locale] ?? MOBILE_AGENT_COPY.zh;
  const template = table[key] ?? key;
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce(
    (value, [name, replacement]) => value.replaceAll(`{{${name}}}`, replacement),
    template,
  );
}

/** Convenience `t` helper bound to the active locale. */
export const t = translateAgentMobileText;
